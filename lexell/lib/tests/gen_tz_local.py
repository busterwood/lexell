#!/usr/bin/env python3
"""Regenerates lib/tests/run/tz_local.lxl: tz.Zone.instantOf (a local date and
time in a zone to an instant) checked against Python's zoneinfo with fold 0,
which has PostgreSQL's rules: a local time that happens twice is the earlier
instant, one in a gap is read with the offset before the change.

    python3 lexell/lib/tests/gen_tz_local.py

For each zone of gen_tz.py, the local times across each transition in 2025 to
2028 and in 1970 and 1945 (every 10 minutes from 3 hours before the change to 3
hours after it, in local time, and the seconds either side of both ends of the
gap or overlap), and seeded random local times from 1900 to 2100.
"""
import datetime
import os
import random
import sys
from zoneinfo import ZoneInfo

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_tz  # noqa: E402

OUT = os.path.join(HERE, 'run', 'tz_local.lxl')


def instant(zone, local):
    return int(local.replace(tzinfo=ZoneInfo(zone), fold=0).timestamp())


def locals_near(zone, t):
    """Local times (naive datetimes) around the transition at Unix second t."""
    z = ZoneInfo(zone)
    before = datetime.datetime.fromtimestamp(t - 1, datetime.timezone.utc).astimezone(z).replace(tzinfo=None)
    after = datetime.datetime.fromtimestamp(t, datetime.timezone.utc).astimezone(z).replace(tzinfo=None)
    out = set()
    for edge in (before, after):
        for d in (-1, 0, 1):
            out.add(edge + datetime.timedelta(seconds=d))
    lo = min(before, after) - datetime.timedelta(hours=3)
    hi = max(before, after) + datetime.timedelta(hours=3)
    x = lo.replace(minute=lo.minute // 10 * 10, second=0)
    while x <= hi:
        out.add(x)
        x += datetime.timedelta(minutes=10)
    return out


def rows():
    rng = random.Random(20261111)
    out = []
    for zone in gen_tz.ZONES:
        if zone in gen_tz.UNSTABLE:
            continue
        ls = set()
        for t in gen_tz.transitions(zone, [1945, 1970, 2025, 2026, 2027, 2028]):
            ls.update(locals_near(zone, t))
        for _ in range(30):
            ls.add(datetime.datetime(1900, 1, 1) + datetime.timedelta(seconds=rng.randrange(0, 200 * 365 * 86400)))
        for l in sorted(ls):
            out.append((zone, l, instant(zone, l)))
    return out


PROGRAM = '''
// Runs tz.Zone.instantOf on every row of ROWS (zone, local date-time) and
// prints the zone, the local date-time and the instant's Unix seconds.

fn main() {
    let text: str = ROWS
    var zones: Map[str, tz.Zone] = newMap()
    for row in strings.lines(&text) {
        match strings.cut(row, "\\t") {
            Some(a) {
                if !zones.has(&a.before.toStr()) {
                    match tz.load(a.before.toStr()) {
                        Ok(z) { zones.put(a.before.toStr(), z) }
                        Err(e) {
                            println("load " + a.before.toStr() + ": " + e)
                            exit(1)
                        }
                    }
                }
                let l = time.parseLocalDateTime(a.after.toStr()).unwrap()
                let t = zones.at(a.before.toStr()).instantOf(l)
                println(a.before.toStr() + " " + a.after.toStr() + " " + t.sec.toStr())
            }
            None { println("bad row") }
        }
    }
}
'''


def main():
    data = rows()
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// tz: Zone.instantOf, a local date and time to an instant, checked against\n')
        f.write('// Python zoneinfo with fold 0 (generated by lib/tests/gen_tz_local.py): an\n')
        f.write('// overlap gives the earlier instant, a gap the offset before the change.\n')
        f.write('// Each expect line: the zone, the local date-time, the instant in Unix seconds.\n')
        for zone, l, sec in data:
            f.write('// expect: %s %s %d\n' % (zone, l.strftime('%Y-%m-%dT%H:%M:%S'), sec))
        f.write('\nimport "tz"\nimport "time"\nimport "strings"\n\n')
        body = '\\n'.join('%s\\t%s' % (zone, l.strftime('%Y-%m-%dT%H:%M:%S')) for zone, l, sec in data)
        f.write('const ROWS = "' + body + '"\n')
        f.write(PROGRAM)
    print('%s: %d rows' % (OUT, len(data)))


if __name__ == '__main__':
    main()
