#!/usr/bin/env python3
"""Regenerates lib/tests/run/time_arith.lxl: the calendar and duration
arithmetic of time.lxl checked against Python.

    python3 lexell/lib/tests/gen_time_arith.py

- Date.addDays, daysUntil and dayOfYear against datetime.date;
- Date.addMonths against a month count with the day clamped to the month's
  last (calendar.monthrange);
- Date.until: d.plusPeriod(d.until(o)) == o, and the period's months under 12
  with every part of one sign (checked in the program);
- Duration plus, minus, times and roundTo(1000) against exact integers in
  nanoseconds, halves rounded away from zero;
- LocalDateTime.plusInterval: the months (clamped), then the days, then the
  time, against datetime.
Seeded random values; years 1 to 9999 (datetime's range).
"""
import calendar
import datetime
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'run', 'time_arith.lxl')
NS = 10 ** 9


def add_months(d, n):
    m0 = d.year * 12 + (d.month - 1) + n
    y, m = divmod(m0, 12)
    last = calendar.monthrange(y, m + 1)[1]
    return datetime.date(y, m + 1, min(d.day, last))


def rand_date(rng, lo=1, hi=9999):
    return datetime.date(lo, 1, 1) + datetime.timedelta(days=rng.randrange((datetime.date(hi, 12, 31) - datetime.date(lo, 1, 1)).days))


def dur_str(ns):
    sec, nsec = divmod(ns, NS)
    return '%d.%09d' % (sec, nsec)


def round_away(ns, unit):
    a = abs(ns)
    q, r = divmod(a, unit)
    if 2 * r >= unit:
        q += 1
    return q * unit if ns >= 0 else -q * unit


def main():
    rng = random.Random(20261111)
    rows, exp = [], []
    for _ in range(300):
        d = rand_date(rng, 100, 9900)
        n = rng.randrange(-30000, 30000)
        rows.append('days %s %d' % (d.isoformat(), n))
        exp.append('days %s %d %s' % (d.isoformat(), n, (d + datetime.timedelta(days=n)).isoformat()))
    for _ in range(300):
        d = rand_date(rng, 30, 9970)
        if rng.random() < 0.4:      # month ends, where clamping happens
            last = calendar.monthrange(d.year, d.month)[1]
            d = d.replace(day=last)
        n = rng.randrange(-300, 300)
        rows.append('months %s %d' % (d.isoformat(), n))
        exp.append('months %s %d %s' % (d.isoformat(), n, add_months(d, n).isoformat()))
    for _ in range(200):
        a, b = rand_date(rng), rand_date(rng)
        rows.append('until %s %s' % (a.isoformat(), b.isoformat()))
        exp.append('until %s %s %d ok' % (a.isoformat(), b.isoformat(), (b - a).days))
    for _ in range(100):
        d = rand_date(rng)
        rows.append('yday %s' % d.isoformat())
        exp.append('yday %s %d' % (d.isoformat(), d.timetuple().tm_yday))
    for _ in range(300):
        x = rng.randrange(-10 ** 21, 10 ** 21)
        y = rng.randrange(-10 ** 21, 10 ** 21)
        k = rng.randrange(-1000, 1000)
        rows.append('dur %s %s %d' % (dur_str(x), dur_str(y), k))
        exp.append('dur %s %s %d %s %s %s %s' % (dur_str(x), dur_str(y), k, dur_str(x + y), dur_str(x - y), dur_str(x * k),
                                                 dur_str(round_away(x, 1000))))
    for _ in range(300):
        base = datetime.datetime.combine(rand_date(rng, 100, 9800), datetime.time()) + datetime.timedelta(microseconds=rng.randrange(86400 * 10 ** 6))
        months = rng.randrange(-500, 500)
        days = rng.randrange(-5000, 5000)
        us = rng.randrange(-10 ** 13, 10 ** 13)
        d = add_months(base.date(), months)
        r = datetime.datetime.combine(d, base.time()) + datetime.timedelta(days=days, microseconds=us)
        rows.append('ival %s %d %d %d' % (base.isoformat(), months, days, us))
        exp.append('ival %s %d %d %d %s' % (base.isoformat(), months, days, us, r.isoformat()))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// time: date, duration and interval arithmetic, checked against Python\n')
        f.write('// (generated by lib/tests/gen_time_arith.py).\n')
        for e in exp:
            f.write('// expect: %s\n' % e)
        f.write('\nimport "time"\nimport "strings"\n\n')
        f.write('const ROWS = "' + '\\n'.join(rows) + '"\n')
        f.write(PROGRAM)
    print('%s: %d rows' % (OUT, len(rows)))


PROGRAM = '''
fn date(s: &str): time.Date { return time.parseDate(s.toStr()).unwrap() }

fn num(s: &str): int { return strings.parseInt(s.toStr()).unwrap() }

// "123.000000456" as a Duration (the seconds may be negative; the fraction never is)
fn dur(s: &str): time.Duration {
    let p = strings.cut(s, ".").unwrap()
    return time.duration(num(&p.before), num(&p.after))
}

fn durStr(d: time.Duration): str { return d.sec.toStr() + "." + strings.padLeft(d.nsec.toStr(), 9, '0') }

// Python's isoformat of a date-time: no fraction when zero, else six digits
fn pyIso(l: time.LocalDateTime): str {
    let base = l.date.toStr() + "T" + strings.padLeft(l.time.hour().toStr(), 2, '0') + ":" +
               strings.padLeft(l.time.minute().toStr(), 2, '0') + ":" + strings.padLeft(l.time.second().toStr(), 2, '0')
    let us = l.time.nano() / 1000
    return if us == 0 { base } else { base + "." + strings.padLeft(us.toStr(), 6, '0') }
}

fn main() {
    let text: str = ROWS
    for row in strings.lines(&text) {
        let f = strings.fields(&row)
        if f[0] == "days" {
            println(row + " " + date(&f[1]).addDays(num(&f[2])).toStr())
        } else if f[0] == "months" {
            println(row + " " + date(&f[1]).addMonths(num(&f[2])).toStr())
        } else if f[0] == "until" {
            let a = date(&f[1])
            let b = date(&f[2])
            let p = a.until(&b)
            let back = a.plusPeriod(p).eq(&b)
            let pos = p.years >= 0 && p.months >= 0 && p.days >= 0
            let neg = p.years <= 0 && p.months <= 0 && p.days <= 0
            let ok = back && (pos || neg) && p.months < 12 && p.months > -12
            println(row + " " + a.daysUntil(b).toStr() + (if ok { " ok" } else { " BAD " + p.toStr() }))
        } else if f[0] == "yday" {
            println(row + " " + date(&f[1]).dayOfYear().toStr())
        } else if f[0] == "dur" {
            let x = dur(&f[1])
            let y = dur(&f[2])
            let k = num(&f[3])
            println(row + " " + durStr(x.plus(y)) + " " + durStr(x.minus(y)) + " " + durStr(x.times(k)) + " " + durStr(x.roundTo(1000)))
        } else if f[0] == "ival" {
            let l = time.parseLocalDateTime(f[1].toStr()).unwrap()
            let i = time.interval(num(&f[2]), num(&f[3]), time.micros(num(&f[4])))
            println(row + " " + pyIso(l.plusInterval(i)))
        }
    }
}
'''

if __name__ == '__main__':
    main()
