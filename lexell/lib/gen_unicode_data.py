#!/usr/bin/env python3
"""Generates lexell/lib/unicode_data.lxl: the Unicode data of the unicode
module, from Go's unicode tables (the same source as regex_unicode.lxl, so
the two modules cannot disagree about a code point's category or case).

    python3 lexell/lib/gen_unicode_data.py [--goroot DIR]

The module holds the 38 general categories, the simple lower/upper mappings
(UnicodeData.txt fields 12 and 13), simple case folding, and the White_Space
property. It deliberately leaves scripts, blocks and category aliases to
regex_unicode.lxl: a program that only classifies text does not pay for them.
"""
import argparse, os, re, sys

import gen_regex_unicode as g

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'unicode_data.lxl')
MAX_RUNE = 0x10FFFF


def convert(case, r, cr):
    lo, _, ds = cr
    delta = ds[case]
    if delta > MAX_RUNE:   # UpperLower: alternate upper and lower from lo
        return lo + (((r - lo) & ~1) | (case & 1))
    return r + delta


def simple_case(cranges, case):
    out = {}
    for cr in cranges:
        lo, hi, _ = cr
        for r in range(lo, hi + 1):
            c = convert(case, r, cr)
            if c != r:
                out[r] = c
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--goroot')
    a = ap.parse_args()
    root = g.goroot(a.goroot)
    src = open(os.path.join(root, 'src', 'unicode', 'tables.go'), encoding='utf-8').read()
    version = re.search(r'const Version = "([^"]+)"', src).group(1)
    tables = g.parse_tables(src)
    varalias = g.parse_var_aliases(src)
    cats = g.parse_map(src, 'Categories')

    def table(name):
        return tables[varalias.get(name, name)]

    # The categories, in the same sorted order as regex_unicode's first 38
    # classes: the unicode module's CAT_* constants are indices into this.
    entries = [(n, cats[n]) for n in sorted(cats)]
    flat, index = [], []
    for n, tvar in entries:
        rs = g.expand(table(tvar))
        start = len(flat) // 2
        for lo, hi in rs:
            flat += [lo, hi]
        index.append((n, start, len(rs)))

    fold = g.simple_fold_all(g.case_ranges(src), g.case_orbit(src))
    keys = sorted(fold)
    lower = simple_case(g.case_ranges(src), 1)
    upper = simple_case(g.case_ranges(src), 0)
    lower_keys = sorted(lower)
    upper_keys = sorted(upper)
    space = g.expand(table('White_Space'))

    out = []
    out.append('// unicode_data: Unicode data for the unicode module (generated; do not edit).')
    out.append('//')
    out.append('// Generated by lexell/lib/gen_unicode_data.py from Go\'s unicode tables')
    out.append('// (src/unicode/tables.go, Unicode %s), the same source as' % version)
    out.append('// regex_unicode.lxl. The data is Unicode\'s (Unicode License v3); the')
    out.append('// table layout follows Go\'s (BSD-3-Clause, Copyright 2009 The Go Authors;')
    out.append('// see NOTICE).')
    out.append('')
    out.append('pub const UNICODE_VERSION = "%s"' % version)
    out.append('pub const MAX_RUNE = 0x10FFFF')
    out.append('')
    out.append('// The 38 general categories (the composite names C, L, LC, M, N, P, S, Z')
    out.append('// included). CLASS_START[i], CLASS_COUNT[i] are a run of (lo, hi) pairs')
    out.append('// in RANGES.')
    out.append('pub const NUM_CATEGORIES = %d' % len(index))
    out.append('pub const CLASS_NAMES: []str = [%s]' % ', '.join('"%s"' % n for n, *_ in index))
    out.append('pub const CLASS_START: []i32 = [%s]' % ', '.join(str(x[1]) for x in index))
    out.append('pub const CLASS_COUNT: []i32 = [%s]' % ', '.join(str(x[2]) for x in index))
    out.append('')
    out.append('// %d pairs.' % (len(flat) // 2))
    out.append('pub const RANGES: []i32 = [')
    out.append(g.ints(flat))
    out.append(']')
    out.append('')
    out.append('// Simple case folding: (r, SimpleFold(r)) for every r that folds, sorted')
    out.append('// by r (%d pairs).' % len(keys))
    out.append('pub const FOLD_PAIRS: []i32 = [')
    fold_flat = []
    for k in keys:
        fold_flat += [k, fold[k]]
    out.append(g.ints(fold_flat))
    out.append(']')
    out.append('')
    out.append('pub const MIN_FOLD = 0x%X' % keys[0])
    out.append('pub const MAX_FOLD = 0x%X' % keys[-1])
    out.append('')
    out.append('// The simple lowercase and uppercase mappings, sorted by code point.')
    out.append('// A code point with no mapping is its own lower/upper form.')
    out.append('pub const LOWER_FROM: []i32 = [')
    out.append(g.ints(lower_keys))
    out.append(']')
    out.append('pub const LOWER_TO: []i32 = [')
    out.append(g.ints([lower[k] for k in lower_keys]))
    out.append(']')
    out.append('pub const UPPER_FROM: []i32 = [')
    out.append(g.ints(upper_keys))
    out.append(']')
    out.append('pub const UPPER_TO: []i32 = [')
    out.append(g.ints([upper[k] for k in upper_keys]))
    out.append(']')
    out.append('')
    out.append('// White_Space, as (lo, hi) pairs.')
    out.append('pub const SPACE: []i32 = [')
    out.append(g.ints([x for lo, hi in space for x in (lo, hi)]))
    out.append(']')
    out.append('')
    out.append('''// The next code point of r's case-folding orbit (r itself when none), as Go's
// unicode.SimpleFold.
pub fn simpleFold(r: int): int {
    if r < MIN_FOLD || r > MAX_FOLD {
        return r
    }
    if r < 0x80 {
        if r >= 0x41 && r <= 0x5A { return r + 32 }     // A-Z
        if r >= 0x61 && r <= 0x7A {                      // a-z
            if r == 0x6B { return 0x212A }               // k -> Kelvin sign
            if r == 0x73 { return 0x17F }                // s -> long s
            return r - 32
        }
        return r
    }
    var lo = 0
    var hi = len(FOLD_PAIRS) / 2
    while lo < hi {
        let m = (lo + hi) / 2
        let k = int(FOLD_PAIRS[2 * m])
        if k == r { return int(FOLD_PAIRS[2 * m + 1]) }
        if k < r { lo = m + 1 } else { hi = m }
    }
    return r
}

// The simple lowercase form of r (UnicodeData.txt field 13); r when unmapped.
pub fn lower(r: int): int {
    var lo = 0
    var hi = len(LOWER_FROM)
    while lo < hi {
        let m = (lo + hi) / 2
        let k = int(LOWER_FROM[m])
        if k == r { return int(LOWER_TO[m]) }
        if k < r { lo = m + 1 } else { hi = m }
    }
    return r
}

// The simple uppercase form of r (UnicodeData.txt field 12); r when unmapped.
pub fn upper(r: int): int {
    var lo = 0
    var hi = len(UPPER_FROM)
    while lo < hi {
        let m = (lo + hi) / 2
        let k = int(UPPER_FROM[m])
        if k == r { return int(UPPER_TO[m]) }
        if k < r { lo = m + 1 } else { hi = m }
    }
    return r
}

// Whether r has the Unicode White_Space property.
pub fn isSpace(r: int): bool {
    var lo = 0
    var hi = len(SPACE) / 2
    while lo < hi {
        let m = (lo + hi) / 2
        if r < int(SPACE[2 * m]) {
            hi = m
        } else if r > int(SPACE[2 * m + 1]) {
            lo = m + 1
        } else {
            return true
        }
    }
    return false
}

// The index of a category in CLASS_NAMES (exact name), or -1.
pub fn classIndex(name: str): int {
    for i in 0..NUM_CATEGORIES {
        if CLASS_NAMES[i] == name { return i }
    }
    return -1
}

// Whether r is in the class (pairs CLASS_START[i] .. + CLASS_COUNT[i]).
pub fn inClass(i: int, r: int): bool {
    var lo = int(CLASS_START[i])
    var hi = lo + int(CLASS_COUNT[i])
    while lo < hi {
        let m = (lo + hi) / 2
        if r < int(RANGES[2 * m]) {
            hi = m
        } else if r > int(RANGES[2 * m + 1]) {
            lo = m + 1
        } else {
            return true
        }
    }
    return false
}''')
    text = '\n'.join(out) + '\n'
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote %s: Unicode %s, %d categories, %d range pairs, %d fold pairs, %d lower, %d upper, %d space ranges' % (
        OUT, version, len(index), len(flat) // 2, len(keys), len(lower), len(upper), len(space)))


if __name__ == '__main__':
    main()
