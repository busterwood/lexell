#!/usr/bin/env python3
"""Writes compiler/rt.lxl: rt.h (the C runtime) as an lxl constant, one str per line.

    python3 lexell/compiler/gen_rt.py           # after changing rt.h; reseed.sh runs it too
    python3 lexell/compiler/gen_rt.py --check   # writes nothing; fails if rt.lxl is not rt.h
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'rt.h')
OUT = os.path.join(HERE, 'rt.lxl')


def lit(s):
    for ch in s:
        if not (32 <= ord(ch) < 127):
            sys.exit(f"gen_rt.py: rt.h has a byte lxl cannot write in a literal: {ord(ch)}")
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    with open(SRC) as f:
        lines = f.read().split('\n')
    out = ["// Generated by gen_rt.py from ref/rt.h: do not edit.",
           "// The C runtime, line by line (joined with newlines it is rt.h byte for byte).",
           "", "pub const RT: []str = ["]
    out += [f"    {lit(x)}," for x in lines]
    out += ["]", ""]
    # the ported libm (lxlmath.inc): added to the C only when a program calls it
    out += ["// lxlmath.inc, the libm of the programs that call it (gen_lxlmath.py).", "pub const RTMATH: []str = ["]
    out += [f"    {lit(x)}," for x in open(os.path.join(HERE, 'lxlmath.inc')).read().split('\n')]
    out += ["]", ""]
    text = '\n'.join(out)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old and '--check' in sys.argv[1:]:
        sys.exit("gen_rt.py: rt.lxl is stale: run lexell/compiler/gen_rt.py after changing rt.h")
    if text != old:
        with open(OUT, 'w') as f:
            f.write(text)


if __name__ == '__main__':
    main()
