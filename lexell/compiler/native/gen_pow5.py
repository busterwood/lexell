#!/usr/bin/env python3
"""Writes native/pow5.inc: for q in [-342, 308], the 128 most significant bits of 5^q, truncated
(never rounded up), with the leading bit set, as flt_pow5[q + 342] = {high 64 bits, low 64 bits}.
rt.c's flt_fast (the Eisel-Lemire algorithm) multiplies a decimal's digits by them. The values are
exact floors, computed with Python's integers; 10^q = 5^q * 2^q, so they serve for powers of ten.

    python3 lexell/compiler/native/gen_pow5.py     # then gen_rtx.py
"""
import os
LO, HI = -342, 308
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pow5.inc')
lines = ['/* Generated by gen_pow5.py: the 128-bit truncated mantissas of 5^q, q = %d .. %d. */' % (LO, HI),
         'static const uint64_t flt_pow5[%d][2] = {' % (HI - LO + 1)]
for q in range(LO, HI + 1):
    if q >= 0:
        v = 5 ** q
        b = v.bit_length()
        v = v << (128 - b) if b < 128 else v >> (b - 128)
    else:
        p = 5 ** -q
        v = (1 << (127 + p.bit_length())) // p
    assert (1 << 127) <= v < (1 << 128)
    lines.append('    {0x%016xULL, 0x%016xULL},   /* 5^%d */' % (v >> 64, v & ((1 << 64) - 1), q))
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print('pow5.inc: %d entries' % (HI - LO + 1))
