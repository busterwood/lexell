def gen(base, name, qfile, out, seed, header):
    if name in NAMED:
        return gen_named(base, name, qfile, out, seed, header)
    db = 'lexdb_gen_' + name
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database if exists ' + db], capture_output=True)
    r = subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'create database ' + db], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('gen_pg.py: ' + r.stderr)
    queries = [l.strip() for l in open(os.path.join(HERE, qfile)) if l.strip() and not l.startswith('#')]
    # one session for them all, as the test runs them (BEGIN ... ROLLBACK spans queries)
    script = 'set timezone = \'UTC\';\n' + ''.join('\\echo @@\n' + q + ';\n' for q in queries)
    r = subprocess.run(['psql', base + ' dbname=' + db, '-X', '-A', '-t', '-F', '|', '-v', 'VERBOSITY=sqlstate', '-f', '-'],
                       input=script, capture_output=True, text=True)
    exp = parse(r.stdout, r.stderr, len(queries))
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database ' + db], capture_output=True)
    path = os.path.join(HERE, 'run', out)
    with open(path, 'w', encoding='utf-8') as f:
        for h in header:
            f.write('// ' + h + '\n')
        for e in exp:
            f.write('// expect: %s\n' % e)
        f.write(PROGRAM.replace('QUERIES_HERE', '\\n'.join(q.replace('\\', '\\\\').replace('"', '\\"') for q in queries))
                .replace('SEED', str(seed)))
    print('%s: %d queries' % (path, len(queries)))


def gen_named(base, name, qfile, out, seed, header):
    db = 'lexdb_gen_' + name
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database if exists ' + db], capture_output=True)
    r = subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'create database ' + db], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('gen_pg.py: ' + r.stderr)
    lines = [l.strip() for l in open(os.path.join(HERE, qfile)) if l.strip() and not l.startswith('#')]
    once = [l.startswith('@once ') for l in lines]
    tx = [l.startswith('@tx ') for l in lines]
    queries = [l[6:] if o else (l[4:] if t else l) for l, o, t in zip(lines, once, tx)]
    # each query's script line (an error names it); an @tx one between BEGIN and ROLLBACK
    script = 'set timezone = \'UTC\';\n'
    at = {}
    n = 1
    for i, q in enumerate(queries):
        script += '\\echo @@\n' + ('begin;\n' if tx[i] else '')
        n += 1 + (1 if tx[i] else 0)
        # an "@tx" line of several statements ("a; b"): the answer is the last one's (the others' output goes nowhere)
        stmts = q.split('; ') if tx[i] else [q]
        for j, st in enumerate(stmts):
            if j < len(stmts) - 1:
                script += '\\o /dev/null\n' + st + ';\n\\o\n'
                at[n + 2] = i
                n += 3
            else:
                script += st + ';\n'
                at[n + 1] = i
                n += 1
        if tx[i]:
            script += 'rollback;\n'
            n += 1
    r = subprocess.run(['psql', base + ' dbname=' + db, '-X', '-A', '-F', '|', '-P', 'footer=off', '-v', 'VERBOSITY=sqlstate', '-f', '-'],
                       input=script, capture_output=True, text=True)
    parts = r.stdout.split('@@\n')[1:]
    exp = []
    for i, q in enumerate(queries):
        body = parts[i] if i < len(parts) else ''
        ls = body.split('\n')
        if ls and ls[-1] == '':
            ls.pop()
        if tx[i]:
            # BEGIN, the answer, ROLLBACK; a DML's RETURNING rows without its tag (as lexdb's program shows them)
            ls = [x for x in ls[1:-1]]
            if ls and len(ls) > 1 and re.match(r'^(INSERT|UPDATE|DELETE|MERGE) ', ls[-1]):
                ls.pop()
        if q.lower().startswith(ROWS) or (tx[i] and q.split('; ')[-1].lower().startswith(ROWS)) or (tx[i] and len(ls) > 0 and ' returning ' in q.lower()):
            exp.append((ls[0] if ls else '') + ': ' + ';'.join(ls[1:]))
        else:
            exp.append(';'.join(ls))
    for e in r.stderr.split('\n'):
        m = re.match(r'psql:<stdin>:(\d+): ERROR:\s+(\S+)', e)
        if m:
            q = at.get(int(m.group(1)), -1)
            if 0 <= q < len(queries):
                exp[q] = 'ERROR ' + m.group(2)
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database ' + db], capture_output=True)
    path = os.path.join(HERE, 'run', out)
    with open(path, 'w', encoding='utf-8') as f:
        for h in header:
            f.write('// ' + h + '\n')
        for e, o in zip(exp, once):
            f.write('// expect: %s%s\n' % ('' if o else 'same: ', e))
        f.write(PROGRAM_NAMED.replace('QUERIES_HERE', '\\n'.join(l.replace('\\', '\\\\').replace('"', '\\"') for l in lines))
                .replace('SEED', str(seed)))
    print('%s: %d queries' % (path, len(queries)))


def parse(out, err, n):
    """Each query's result from psql's output: rows after its @@ marker (or
    its tag when it has none), or ERROR and the SQLSTATE psql printed for it."""
    parts = out.split('@@\n')[1:]
    errs = [l for l in err.split('\n') if l.startswith('psql:')]
    exp = []
    for i in range(n):
        body = parts[i] if i < len(parts) else ''
        # each row ends with a newline: a row of one empty text is an empty line
        lines = body.split('\n')
        if lines and lines[-1] == '':
            lines.pop()
        exp.append(';'.join(lines))
    # errors: psql names the line of the script; map line to query
    for e in errs:
        m = re.match(r'psql:<stdin>:(\d+): ERROR:\s+(\S+)', e)
        if m:
            line = int(m.group(1))
            q = (line - 2) // 2       # line 1 the SET; then \\echo and the query per query
            if 0 <= q < n:
                exp[q] = 'ERROR ' + m.group(2)
    return exp


