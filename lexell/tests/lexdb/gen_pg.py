def psql(conn, db, sql, extra=()):
    return subprocess.run(['psql', conn + ' dbname=' + db, '-X', '-At', '-F', '|', '-R', ';', '-v', 'VERBOSITY=sqlstate',
                           '-c', 'set timezone = \'UTC\'', '-c', sql] + list(extra), capture_output=True, text=True)


def main():
    conn = sys.argv[1] if len(sys.argv) > 1 else ''
    base = ' '.join(p for p in conn.split() if not p.startswith('dbname='))
    for name in (sys.argv[2:] or list(SUITES)):
        gen(base, name, *SUITES[name])


def gen(base, name, qfile, out, seed, header):
    db = 'lexdb_gen_' + name
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database if exists ' + db], capture_output=True)
    r = subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'create database ' + db], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('gen_pg.py: ' + r.stderr)
    queries = [l.strip() for l in open(os.path.join(HERE, qfile)) if l.strip() and not l.startswith('#')]
    # one session for them all, as the test runs them (BEGIN ... ROLLBACK spans queries)
    script = 'set timezone = \'UTC\';\n' + ''.join('\\echo @@\n' + q + ';\n' for q in queries)
    r = subprocess.run(['psql', base + ' dbname=' + db, '-X', '-A', '-t', '-F', '|', '-v', 'VERBOSITY=sqlstate', '-f', '-'],
                       input=script, capture_output=True, text=True)
    exp = parse(r.stdout, r.stderr, len(queries))
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database ' + db], capture_output=True)
    path = os.path.join(HERE, 'run', out)
    with open(path, 'w', encoding='utf-8') as f:
        for h in header:
            f.write('// ' + h + '\n')
        for e in exp:
            f.write('// expect: %s\n' % e)
        f.write(PROGRAM.replace('QUERIES_HERE', '\\n'.join(q.replace('\\', '\\\\').replace('"', '\\"') for q in queries))
                .replace('SEED', str(seed)))
    print('%s: %d queries' % (path, len(queries)))


def parse(out, err, n):
    """Each query's result from psql's output: rows after its @@ marker (or
    its tag when it has none), or ERROR and the SQLSTATE psql printed for it."""
    parts = out.split('@@\n')[1:]
    errs = [l for l in err.split('\n') if l.startswith('psql:')]
    exp = []
    for i in range(n):
        body = parts[i] if i < len(parts) else ''
        # each row ends with a newline: a row of one empty text is an empty line
        lines = body.split('\n')
        if lines and lines[-1] == '':
            lines.pop()
        exp.append(';'.join(lines))
    # errors: psql names the line of the script; map line to query
    for e in errs:
        m = re.match(r'psql:<stdin>:(\d+): ERROR:\s+(\S+)', e)
        if m:
            line = int(m.group(1))
            q = (line - 2) // 2       # line 1 the SET; then \\echo and the query per query
            if 0 <= q < n:
                exp[q] = 'ERROR ' + m.group(2)
    return exp


PROGRAM = '''import "strings"
import "../../../cmd/lexdb_store"
import "../../../cmd/lexdb_disk"
import "../../../cmd/lexdb_exec"

const QUERIES = "QUERIES_HERE"

// every row of the last result, columns joined by |, rows by ;; or the tag
fn show(s: mut &lexdb_exec.Session, q: &str): str {
    match s.exec(q) {
        Ok(rs) {
            let r = &rs[len(rs) - 1]
            if !r.hasRows { return r.tag }
            var rows: []str = []
            for row in r.rows {
                var cells: []str = []
                for v in row { append(mut &cells, lexdb_exec.text(&v)) }
                append(mut &rows, strings.join(&cells, "|"))
            }
            // psql shows a statement's tag after its RETURNING rows, not a SELECT's
            if r.tag != "" && !strings.startsWith(r.tag, "SELECT") && r.tag != "SHOW" { append(mut &rows, r.tag) }
            return strings.join(&rows, ";")
        }
        Err(e) { return "ERROR " + e.state }
    }
}

fn body(st: lexdb_store.Store): int {
    lexdb_exec.bootstrap(&st).unwrap()
    var s = lexdb_exec.newSession(st)
    let text: str = QUERIES
    for q in strings.lines(&text) { println(show(mut &s, &q)) }
    s.close()
    return 0
}

fn main() {
    lexdb_store.run(lexdb_disk.sim(SEED), lexdb_store.Options{cacheBytes: 16 * 1024 * 1024, segBytes: 256 * 1024, ckptBytes: 128 * 1024,
                                                           snapNodes: 50000, bufferedPages: false}, body).unwrap()
}
'''

if __name__ == '__main__':
    main()
