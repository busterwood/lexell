#!/usr/bin/env python3
"""Regenerates lexdb's replay of what VS Code's SQL Server extension sends
(tests/lexdb/run/tds_vscode.lxl): every distinct statement of a session of
SQL Tools Service, the extension's engine (vscode_queries.txt, recorded from
SQL Server 2022 by an Extended Events trace), run on the oracle
(tools/mssql_container.sh) and through lexdb's TDS endpoint, against the
same schema (vscode_schema.sql). design/lexdb-tds.md, section 13.

    python3 lexell/tests/lexdb/gen_vscode.py [--compiler lexell/compiler/out/lxlc] [--lexdb-only]

As gen_mssql.py's tests, the test program is the generator's too: run with
LEXDB_MSSQL set it talks to that server (the oracle's database demo) and
prints its answers, which become the program's ORACLE; run without it, it
runs the statements through lexdb (in the same process) and prints, for
each, "ok" when lexdb's answer is the oracle's, else how they differ: those
lines are the expect lines. So the test passes while lexdb answers as it did
when it was generated, and its expect lines say which statements match.
--lexdb-only keeps the oracle's answers in the test file and makes the
expect lines again (no container needed).

An answer: per result set its columns (name:type, as TDS gives them) and
rows, or a statement's row count; or the error's number. Values that differ
between servers by nature are masked: ids, sids, guids, dates and times;
the database's name ({db}), the login's ({login}), the machine's ({host}); a
uniqueidentifier's;
constraint names either server made up ({name}). The statements' {db},
{pk:t} and {uq:t} are the server's own (its database, t's primary key's or
unique constraint's name, from sys.indexes).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, 'run', 'tds_vscode.lxl')
HEADER = [
    'lexdb over TDS: what VS Code\'s SQL Server extension sends (SQL Tools Service and SMO: connect,',
    'Object Explorer, IntelliSense), replayed against SQL Server 2022 and lexdb (generated by',
    'tests/lexdb/gen_vscode.py from vscode_queries.txt; design/lexdb-tds.md, section 13). Each',
    'expect line: a statement\'s answer the same as the oracle\'s (ok), or how it differs.',
]


def lxl_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')


def unquote(s, i):
    """N'...' at s[i:]: its text and the index after it."""
    if s[i] in 'Nn': i += 1
    assert s[i] == "'", s[i:i + 20]
    i += 1
    out = []
    while True:
        j = s.index("'", i)
        out.append(s[i:j])
        if j + 1 < len(s) and s[j + 1] == "'":
            out.append("'")
            i = j + 2
            continue
        return ''.join(out), j + 1


def rpc_parts(text):
    """exec sp_executesql N'stmt',N'decls',@p=N'v',...: [stmt, decls, name, value, ...]."""
    i = len('exec sp_executesql ')
    stmt, i = unquote(text, i)
    parts = [stmt]
    while i < len(text) and text[i] == ',':
        i += 1
        name = ''
        m = re.match(r'(@\w+)=', text[i:])
        if m:
            name = m.group(1)
            i += len(m.group(0))
        v, i = unquote(text, i)
        if name: parts += [name, v]
        else: parts.append(v)
    assert text[i:].strip() == '', text[i:i + 40]
    return parts


def queries():
    out = []
    cur = None
    for line in open(os.path.join(HERE, 'vscode_queries.txt'), encoding='utf-8'):
        m = re.match(r'^-- #(\d+) (rpc|batch) (\S+)$', line.rstrip('\n'))
        if m:
            cur = [m.group(2), []]
            out.append(cur)
        elif cur is not None:
            cur[1].append(line)
    res = []
    for kind, lines in out:
        text = ''.join(lines).rstrip('\n')
        if kind == 'rpc':
            res.append('\x02' + '\x02'.join(rpc_parts(text)))
        else:
            res.append(text)
    return res


def schema():
    batches, cur = [], []
    for line in open(os.path.join(HERE, 'vscode_schema.sql'), encoding='utf-8'):
        if line.strip().upper() == 'GO':
            batches.append(''.join(cur))
            cur = []
        else:
            cur.append(line)
    return [b for b in batches if b.strip()]


def program(qs, oracle):
    return (PROGRAM.replace('SCHEMA_HERE', lxl_str('\x01'.join(schema())))
            .replace('QUERIES_HERE', lxl_str('\x01'.join(qs)))
            .replace('ORACLE_HERE', lxl_str('\n'.join(oracle))))


def build(compiler, src, tmp):
    exe = os.path.join(tmp, 'gen')
    # compiled where it lives, for its imports
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(src)
    r = subprocess.run([compiler, OUT, '--native', '-o', exe], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('gen_vscode.py: compile: ' + r.stdout + r.stderr)
    return exe


def oracle_answers():
    prev = open(OUT, encoding='utf-8').read()
    m = re.search(r'^const ORACLE = "(.*)"$', prev, re.M)
    s = m.group(1)
    s = re.sub(r'\\(.)', lambda m: {'n': '\n', 'r': '\r', 't': '\t'}.get(m.group(1), m.group(1)), s)
    return s.split('\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--compiler', default=os.path.join(ROOT, 'compiler', 'out', 'lxlc'))
    ap.add_argument('--lexdb-only', action='store_true')
    a = ap.parse_args()
    qs = queries()
    with tempfile.TemporaryDirectory() as tmp:
        if a.lexdb_only:
            oracle = oracle_answers()
        else:
            dsn = open(os.path.expanduser('~/.obo-mssql-dsn')).read().strip()
            sql = [os.path.join(ROOT, 'tools', 'mssql_container.sh'), 'sql', '-d', 'master', '-Q',
                   "IF DB_ID('demo') IS NULL CREATE DATABASE demo"]
            r = subprocess.run(sql, capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit('gen_vscode.py: ' + r.stdout + r.stderr)
            exe = build(a.compiler, program(qs, []), tmp)
            env = dict(os.environ, LEXDB_MSSQL=re.sub(r';?Database=[^;]*', '', dsn, flags=re.I) + ';Database=demo')
            r = subprocess.run([exe], capture_output=True, text=True, env=env, cwd=tmp)
            if r.returncode != 0:
                sys.exit('gen_vscode.py: oracle: ' + r.stdout + r.stderr)
            oracle = r.stdout.rstrip('\n').split('\n')
        if len(oracle) != len(qs):
            sys.exit('gen_vscode.py: %d answers for %d statements' % (len(oracle), len(qs)))
        src = program(qs, oracle)
        exe = build(a.compiler, src, tmp)
        r = subprocess.run([exe], capture_output=True, text=True, cwd=tmp)
        if r.returncode != 0:
            sys.exit('gen_vscode.py: lexdb: ' + r.stdout + r.stderr)
        lines = r.stdout.rstrip('\n').split('\n')
    with open(OUT, 'w', encoding='utf-8') as f:
        for h in HEADER:
            f.write('// ' + h + '\n')
        for l in lines:
            f.write('// expect: %s\n' % l)
        f.write(src)
    print('%s: %s' % (OUT, lines[-1]))


PROGRAM = r'''import "os"
import "strings"
import "task"
import "net"
import "sqlserver"
import "../../../cmd/lexdb_store"
import "../../../cmd/lexdb_disk"
import "../../../cmd/lexdb_exec"
import "../../../cmd/lexdb_wire"
import "../../../cmd/lexdb_tds"

const SCHEMA = "SCHEMA_HERE"
const QUERIES = "QUERIES_HERE"
const ORACLE = "ORACLE_HERE"

// Columns whose values differ between servers by nature: ids, sids, guids.
const MASKED: []str = ["id", "object_id", "principal_id", "parent_object_id", "major_id", "referenced_object_id", "sid", "owner_sid",
                       "servicebrokerguid", "databaseguid", "recoveryforkguid", "processid", "processors"]

fn isTime(t: &str): bool { return t == "datetime" || t == "datetime2" || t == "smalldatetime" || t == "datetimeoffset" }

// A name either server made up for a constraint.
fn madeUp(v: &str): bool {
    for p in ["'PK__", "'UQ__", "'FK__", "'DF__", "'CK__", "'DF_"] { if strings.startsWith(v, p) { return true } }
    for s in ["_pkey'", "_key'", "_fkey'", "_check'"] { if strings.endsWith(v, s) { return true } }
    return false
}

type Ctx = record {
    db: str
    login: str
    host: str
    names: []str        // placeholder, value: {pk:customers}, its name
}

fn cellOf(x: &Ctx, label: &str, typ: &str, v: &str): str {
    if v == "NULL" { return v.toStr() }
    let l = strings.toLowerAscii(label)
    for m in MASKED { if l == m { return "*" } }
    if isTime(typ) { return "<time>" }
    if typ == "uniqueidentifier" { return "<guid>" }
    if v == "'" + x.db + "'" { return "{db}" }
    if v == "'" + x.login + "'" { return "{login}" }
    if v == "'" + x.host + "'" { return "{host}" }
    for i in 0..len(x.names) / 2 { if v == "'" + x.names[2 * i + 1] + "'" { return x.names[2 * i] } }
    if madeUp(v) { return "{name}" }
    return v.toStr()
}

fn rows(x: &Ctx, r: &sqlserver.Rows): str {
    var names: []str = []
    var types: []str = []
    for j in 0..r.columnCount() {
        let c = r.column(j).unwrap()
        append(mut &names, c.name + ":" + c.typeName())
        append(mut &types, c.typeName())
    }
    var out: []str = []
    for i in 0..r.rowCount() {
        var cells: []str = []
        for j in 0..r.columnCount() {
            match r.value(i, j) {
                Ok(v) {
                    let cv = cellOf(x, &r.columnName(j).unwrap(), &types[j], &v.toStr())
                    append(mut &cells, strings.replaceAll(&strings.replaceAll(&cv, "\r", "\\r"), "\n", "\\n"))
                }
                Err(e) { append(mut &cells, "error " + e.code.toStr()) }
            }
        }
        append(mut &out, strings.join(&cells, "|"))
    }
    return "{" + strings.join(&names, ",") + "} " + r.rowCount().toStr() + ": " + strings.join(&out, ";")
}

fn answer(x: &Ctx, r: &sqlserver.Results): str {
    var parts: []str = []
    var shown = 0
    for n in r.counts {
        if n.resultSet >= 0 {
            append(mut &parts, rows(x, &r.sets[n.resultSet]))
            shown += 1
        } else if n.rows >= 0 {
            append(mut &parts, "(" + n.rows.toStr() + ")")
        }
    }
    if shown == 0 { for s in r.sets { append(mut &parts, rows(x, &s)) } }
    if len(parts) == 0 { return "ok" }
    return strings.join(&parts, " / ")
}

fn subst(x: &Ctx, s: &str): str {
    var t = strings.replaceAll(s, "{db}", &x.db)
    for i in 0..len(x.names) / 2 { t = strings.replaceAll(&t, &x.names[2 * i], &x.names[2 * i + 1]) }
    return t
}

// A statement's answer: a batch's, or an RPC's (sp_executesql).
fn run(c: mut &sqlserver.Conn, x: &Ctx, q: &str): str {
    if strings.startsWith(q, "\x02") {
        let ps = strings.split(&q[1..len(q)], "\x02")
        var args: []sqlserver.Arg = [sqlserver.arg("", sqlserver.Value.Text(subst(x, &ps[0]))), sqlserver.arg("", sqlserver.Value.Text(ps[1].toStr()))]
        var i = 2
        while i + 1 < len(ps) {
            append(mut &args, sqlserver.arg(ps[i].toStr(), sqlserver.Value.Text(subst(x, &ps[i + 1]))))
            i += 2
        }
        match c.callProc("sp_executesql", &args, &[]) {
            Ok(r) { return answer(x, &r) }
            Err(e) { return "error " + e.code.toStr() }
        }
    }
    match c.queryAll(subst(x, q), &[]) {
        Ok(r) { return answer(x, &r) }
        Err(e) { return "error " + e.code.toStr() }
    }
}

fn scalar(c: mut &sqlserver.Conn, q: &str): str {
    match c.query(q.toStr(), &[]) {
        Ok(r) {
            if r.rowCount() > 0 {
                match r.text(0, 0) {
                    Ok(t) { return t }
                    Err(_) {}
                }
            }
        }
        Err(_) {}
    }
    return ""
}

// The statements' answers, on the server dsn names.
fn answers(dsn: &str): []str {
    var out: []str = []
    match sqlserver.connect(dsn.toStr()) {
        Ok(c0) {
            var c = c0
            let sch: str = SCHEMA
            for b in strings.split(&sch, "\x01") {
                match c.queryAll(b.toStr(), &[]) {
                    Ok(_) {}
                    Err(e) { append(mut &out, "schema: error " + e.code.toStr() + " " + e.msg) }
                }
            }
            var x = Ctx{db: scalar(mut &c, &"SELECT DB_NAME()"), login: scalar(mut &c, &"SELECT SUSER_SNAME()"),
                        host: scalar(mut &c, &"SELECT CAST(SERVERPROPERTY('MachineName') AS nvarchar(128))"), names: []}
            for t in ["customers", "orders"] {
                for k in ["pk", "uq"] {
                    let w = if k == "pk" { "is_primary_key" } else { "is_unique_constraint" }
                    let n = scalar(mut &c, &("SELECT name FROM sys.indexes WHERE object_id = OBJECT_ID('" + t + "') AND " + w + " = 1"))
                    if len(n) > 0 {
                        append(mut &x.names, "{" + k + ":" + t + "}")
                        append(mut &x.names, n)
                    }
                }
            }
            let qs: str = QUERIES
            for q in strings.split(&qs, "\x01") { append(mut &out, run(mut &c, &x, &q)) }
            c.close()
        }
        Err(e) { append(mut &out, "connect: error " + e.code.toStr() + " " + e.msg) }
    }
    return out
}

// (LEXDB_VSCODE_FULL set: whole answers, for looking into a difference)
fn short(s: &str): str { return if len(s) > 300 && os.env("LEXDB_VSCODE_FULL").isNone() { s[0..300] + " ..." } else { s.toStr() } }

// How lexdb's answer differs from the oracle's: the first part that does.
fn differs(o: &str, l: &str): str {
    let op = strings.split(o, " / ")
    let lp = strings.split(l, " / ")
    for i in 0..min(len(op), len(lp)) {
        if op[i] == lp[i] { continue }
        let oc = strings.indexOf(&op[i], "} ", 0)
        let lc = strings.indexOf(&lp[i], "} ", 0)
        if oc > 0 && lc > 0 && op[i][0..oc] == lp[i][0..lc] {
            // the same columns: the rows
            return "part " + (i + 1).toStr() + " rows: oracle " + short(&op[i][oc + 2..len(op[i])]) + " | lexdb " + short(&lp[i][lc + 2..len(lp[i])])
        }
        return "part " + (i + 1).toStr() + ": oracle " + short(&op[i]) + " | lexdb " + short(&lp[i])
    }
    return "parts: oracle " + len(op).toStr() + " " + short(o) + " | lexdb " + len(lp).toStr() + " " + short(l)
}

fn compare(dsn: &str) {
    let got = answers(dsn)
    let want: str = ORACLE
    let ws = strings.split(&want, "\n")
    var same = 0
    for i in 0..len(got) {
        let w = if i < len(ws) { ws[i] } else { "" }
        if got[i] == w {
            same += 1
            println(i.toStr() + " ok")
        } else {
            println(i.toStr() + " differs: " + differs(&w, &got[i]))
        }
    }
    println("the same as SQL Server's: " + same.toStr() + " of " + len(got).toStr())
}

fn body(st: lexdb_store.Store): int {
    lexdb_exec.bootstrap(&st).unwrap()
    task.scope(fn(s: mut &task.Scope) {
        let ln = net.listen("127.0.0.1:0").unwrap()
        let addr = ln.localAddr()
        lexdb_wire.configure(&st, &lexdb_wire.noAuth()).unwrap()
        let f = s.start(lexdb_tds.acceptLoop, lexdb_tds.AcceptArg{ln: ln, st: st})
        compare(&("Server=127.0.0.1," + addr[10..len(addr)] + ";UID=tester;PWD=x;Database=lexdb;Encrypt=no"))
        { let stop = f }
    })
    return 0
}

fn main() {
    // LEXDB_MSSQL: the oracle, for ORACLE (gen_vscode.py)
    match os.env("LEXDB_MSSQL") {
        Some(dsn) { for a in answers(&dsn) { println(a) } }
        None {
            lexdb_store.run(lexdb_disk.sim(34), lexdb_store.Options{cacheBytes: 64 * 1024 * 1024, segBytes: 256 * 1024, ckptBytes: 128 * 1024,
                                                                  snapNodes: 50000}, body).unwrap()
        }
    }
}
'''

if __name__ == '__main__':
    main()
