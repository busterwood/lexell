def lxl_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def render(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return str(int(v)) if v == int(v) else repr(v)
    if isinstance(v, decimal.Decimal):
        return format(v, 'f')
    if isinstance(v, datetime.datetime):
        s = v.strftime('%Y-%m-%dT%H:%M:%S')
        return "'" + s + ('.%06d' % v.microsecond).rstrip('0') * (1 if v.microsecond else 0) + "'"
    if isinstance(v, datetime.timedelta):
        # INTERVAL DAY TO SECOND as the server's text: '+000000001 12:00:00.000000000'
        us = (v.days * 86400 + v.seconds) * 1000000 + v.microseconds
        sign = '-' if us < 0 else '+'
        us = abs(us)
        d, r = divmod(us, 86400 * 1000000)
        return "'%s%09d %02d:%02d:%02d.%06d000'" % (sign, d, r // 3600000000, r // 60000000 % 60, r // 1000000 % 60, r % 1000000)
    if isinstance(v, oracledb.IntervalYM):
        t = v.years * 12 + v.months
        return "'%s%09d-%02d'" % ('-' if t < 0 else '+', abs(t) // 12, abs(t) % 12)
    if isinstance(v, bytes):
        return "'" + v.hex() + "'"
    if hasattr(v, 'read'):
        v = v.read()
    return "'" + str(v).replace("'", "''") + "'"


def call_answer(cur, n, sql):
    """a statement with n out binds (`@n sql` in a consts test: RETURNING ... INTO :1, ..., or a block setting :1 ...), in a
    transaction rolled back: its row count, then each row of the binds' values (VARCHAR2): "2 = 'a'|'b';NULL|'c'" (tns_retold)"""
    vs = [cur.var(oracledb.DB_TYPE_VARCHAR, 4000, arraysize=100) for _ in range(n)]
    try:
        cur.execute(sql, vs)
        cols = []
        for v in vs:
            x = v.getvalue()
            cols.append(x if isinstance(x, list) else [x])
        rows = list(zip(*cols)) if cols else []
        r = str(max(cur.rowcount, 0)) + ' = ' + ';'.join('|'.join(render(x) for x in row) for row in rows)
    except oracledb.DatabaseError as e:
        m = re.match(r'ORA-(\d+)', str(e))
        r = 'error ' + str(int(m.group(1))) if m else 'error ' + str(e)
    cur.connection.rollback()
    return r


def answer(cur, kind, sql, tx=False):
    if kind.startswith('@'):
        return call_answer(cur, int(kind[1:]), sql)
    if kind in ('t', 'u'):
        # statements and queries in one transaction, rolled back (t) or committed (u)
        parts = [answer(cur, 'q' if p.lower().startswith('select') else 'x', p, True) for p in sql.split(' ;; ')]
        if kind == 't':
            cur.connection.rollback()
        else:
            cur.connection.commit()
        return ' / '.join(parts)
    try:
        cur.execute(sql)
        if kind == 'x':
            n = str(max(cur.rowcount, 0))
            if not tx:
                cur.connection.commit()     # lexdb's client commits each statement it runs outside a transaction
            return n
        names = [d[0] for d in cur.description]
        rows = cur.fetchall()
        return ','.join(names) + ' = ' + ';'.join('|'.join(render(v) for v in r) for r in rows)
    except oracledb.DatabaseError as e:
        msg = str(e.args[0].message if hasattr(e.args[0], 'message') else e)
        import re
        m = re.match(r'ORA-(\d+)', msg)
        return 'error ' + str(int(m.group(1))) if m else 'error ' + msg


