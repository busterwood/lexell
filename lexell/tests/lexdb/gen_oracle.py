#!/usr/bin/env python3
"""Regenerates lexdb's tests that are checked against Oracle: each a file of statements
and queries, run on the oracle (Oracle Database Free: tools/oracle_container.sh) through
python-oracledb, and a test that runs them through lexdb's TNS endpoint (in the same
process) with lib/oracle, expecting the oracle's answers. design/lexdb-oracle.md, O4.

    python3 lexell/tests/lexdb/gen_oracle.py --dsn app/PASSWORD@127.0.0.1:1521/FREEPDB1 [SUITE ...]

The queries file (oracle_catalog_queries.txt) has a line for each: `x<TAB>label<TAB>statement`
(its row count is the answer) or `q<TAB>label<TAB>query` (its columns' names and rows:
names,... = v|v;v|v with NULL as NULL and text quoted), or `error N` for an ORA- error.
The account must be able to create tables, views and sequences (the container's APP) and to
read V$INSTANCE, V$DATABASE, V$SESSION, V$PARAMETER, V$NLS_PARAMETERS and DBA_TABLES (as SYS:
grant select on sys.v_$session to app; ... as tools/oracle_container.sh grants does for V$MYSTAT).
The test program is the generator's too: lexdb is made to connect as app/app (trust).
Needs python-oracledb (pip install oracledb).
"""
import argparse, datetime, decimal, os, sys
import oracledb

HERE = os.path.dirname(os.path.abspath(__file__))
SUITES = {
    'catalog': ('oracle_catalog_queries.txt', 'tns_catalog.lxl', [
        'lexdb over TNS: Oracle\'s catalog views as drivers and tools query them (design/lexdb-oracle.md,',
        'O4), checked against Oracle Database Free (generated by tests/lexdb/gen_oracle.py from',
        'oracle_catalog_queries.txt): V$VERSION, V$SESSION, V$PARAMETER, NLS_*_PARAMETERS, USER_/ALL_',
        'TABLES, TAB_COLUMNS, INDEXES, IND_COLUMNS, CONSTRAINTS, CONS_COLUMNS, OBJECTS, SEQUENCES,',
        'VIEWS, USERS, DICTIONARY, SYS_CONTEXT and the queries of JDBC\'s DatabaseMetaData. Each answer is a',
        'label, the columns\' names, then the rows (or error and the ORA- number).']),
    'merge': ('oracle_merge_queries.txt', 'tns_merge.lxl', [
        'lexdb over TNS: MERGE (design/lexdb-oracle.md, O3), checked against Oracle Database Free (generated',
        'by tests/lexdb/gen_oracle.py from oracle_merge_queries.txt): an upsert, UPDATE ... WHERE and DELETE',
        'WHERE, INSERT ... WHERE, one clause alone and in either order, sources that are tables, DUAL,',
        'subqueries and joins, ORA-30926 for a target row matched twice, NULL keys and the empty string, a',
        'table without a key, identity and sequence defaults, ORA-38104, constraints failing the whole',
        'statement, a transaction rolled back, and the errors of bad statements. Each answer is a label, then',
        'the row count, or the columns\' names and rows, or error and the ORA- number.'],
        ['m_kid', 'm_par', 'm_kl', 'm_nk', 'm_dup', 'm_sqt', 'm_idt', 'm_src', 'm_tgt'], ['m_sq']),
}


def lxl_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def render(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return str(int(v)) if v == int(v) else repr(v)
    if isinstance(v, decimal.Decimal):
        return format(v, 'f')
    if isinstance(v, datetime.datetime):
        s = v.strftime('%Y-%m-%dT%H:%M:%S')
        return "'" + s + ('.%06d' % v.microsecond if v.microsecond else '') + "'"
    if isinstance(v, bytes):
        return "'" + v.hex() + "'"
    if hasattr(v, 'read'):
        v = v.read()
    return "'" + str(v).replace("'", "''") + "'"


def answer(cur, kind, sql, tx=False):
    if kind in ('t', 'u'):
        # statements and queries in one transaction, rolled back (t) or committed (u)
        parts = [answer(cur, 'q' if p.lower().startswith('select') else 'x', p, True) for p in sql.split(' ;; ')]
        if kind == 't':
            cur.connection.rollback()
        else:
            cur.connection.commit()
        return ' / '.join(parts)
    try:
        cur.execute(sql)
        if kind == 'x':
            n = str(max(cur.rowcount, 0))
            if not tx:
                cur.connection.commit()     # lexdb's client commits each statement it runs outside a transaction
            return n
        names = [d[0] for d in cur.description]
        rows = cur.fetchall()
        return ','.join(names) + ' = ' + ';'.join('|'.join(render(v) for v in r) for r in rows)
    except oracledb.DatabaseError as e:
        msg = str(e.args[0].message if hasattr(e.args[0], 'message') else e)
        import re
        m = re.match(r'ORA-(\d+)', msg)
        return 'error ' + str(int(m.group(1))) if m else 'error ' + msg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dsn', required=True, help='user/password@host:port/service')
    ap.add_argument('suites', nargs='*')
    a = ap.parse_args()
    u, rest = a.dsn.split('/', 1)
    pw, dsn = rest.rsplit('@', 1)
    for name in (a.suites or list(SUITES)):
        gen(oracledb.connect(user=u, password=pw, dsn=dsn), name, *SUITES[name])


def gen(conn, name, qfile, out, header, tables=(), sequences=()):
    cur = conn.cursor()
    items = []
    for l in open(os.path.join(HERE, qfile), encoding='utf-8'):
        l = l.rstrip('\n')
        if not l.strip() or l.startswith('#'):
            continue
        k, label, sql = l.split('\t', 2)
        items.append((k, label, sql))
    # leftovers of a failed run
    for s in ['drop view emp_v', 'drop table tys purge', 'drop table idt purge', 'drop table emp purge', 'drop table dept purge',
              'drop sequence emp_seq'] + ['drop table %s purge' % t for t in tables] + ['drop sequence %s' % q for q in sequences]:
        try:
            cur.execute(s)
        except oracledb.DatabaseError:
            pass
    expects = [(k, label, sql, answer(cur, k, sql)) for k, label, sql in items]
    with open(os.path.join(HERE, 'run', out), 'w', encoding='utf-8') as f:
        for h in header:
            f.write('// ' + h + '\n')
        for k, label, sql, ans in expects:
            f.write('// expect: ' + label + ': ' + ans + '\n')
        f.write(PROGRAM.replace('CALLS_HERE', '\n'.join(
            '    %s(mut &c, "%s", "%s")' % (k, lxl_str(label), lxl_str(sql)) for k, label, sql, _ in expects)))
    print('wrote', out, len(expects), 'answers')


PROGRAM = r'''import "task"
import "net"
import "strings"
import "oracle"
import "sqldialect"
import "../../../cmd/lexdb_store"
import "../../../cmd/lexdb_disk"
import "../../../cmd/lexdb_exec"
import "../../../cmd/lexdb_tns"

fn values(rows: &oracle.Rows, row: int): str {
    var out: []str = []
    for i in 0..rows.columnCount() {
        match rows.isNull(row, i) {
            Ok(n) {
                if n { append(mut &out, "NULL") } else {
                    match rows.value(row, i) {
                        Ok(v) { append(mut &out, v.toStr()) }
                        Err(e) { append(mut &out, "error " + e.code.toStr() + " " + e.msg) }
                    }
                }
            }
            Err(e) { append(mut &out, "error " + e.code.toStr()) }
        }
    }
    return strings.join(&out, "|")
}

// A query: its columns' names, then its rows; or error and the number.
fn qtext(c: mut &oracle.Conn, sql: &str): str {
    match c.query(sql.toStr(), &[]) {
        Ok(rows) {
            var names: []str = []
            for j in 0..rows.columnCount() { append(mut &names, rows.columnName(j).unwrap()) }
            var rs: []str = []
            for i in 0..rows.rowCount() { append(mut &rs, values(&rows, i)) }
            return strings.join(&names, ",") + " = " + strings.join(&rs, ";")
        }
        Err(e) { return "error " + e.code.toStr() }
    }
}

// A statement: its row count, or error and the number.
fn xtext(c: mut &oracle.Conn, sql: &str): str {
    match c.run(sql.toStr(), &[]) {
        Ok(n) { return n.toStr() }
        Err(e) { return "error " + e.code.toStr() }
    }
}

fn q(c: mut &oracle.Conn, label: &str, sql: &str) { println(label + ": " + qtext(c, sql)) }
fn x(c: mut &oracle.Conn, label: &str, sql: &str) { println(label + ": " + xtext(c, sql)) }

// Statements and queries ("a ;; b ;; c") in one transaction, rolled back (t) or committed (u): each answer, joined by " / ".
fn tx(c: mut &oracle.Conn, label: &str, sqls: &str, commit: bool) {
    var out: []str = []
    let r = c.transaction(fn(c2: mut &oracle.Conn): Result[int, oracle.Error] {
        for part in strings.split(sqls, " ;; ") {
            if strings.startsWith(&strings.toLowerAscii(part), "select") { append(mut &out, qtext(c2, part)) } else { append(mut &out, xtext(c2, part)) }
        }
        if !commit { return Err(sqldialect.inputError("rolled back")) }
        return Ok(0)
    })
    println(label + ": " + strings.join(&out, " / "))
}
fn t(c: mut &oracle.Conn, label: &str, sqls: &str) { tx(c, label, sqls, false) }
fn u(c: mut &oracle.Conn, label: &str, sqls: &str) { tx(c, label, sqls, true) }

fn connect(s: &str): oracle.Conn {
    match oracle.connect(s.toStr()) {
        Ok(c) { return c }
        Err(e) {
            println("connect: error " + e.code.toStr() + " " + e.msg)
            exit(1)
        }
    }
}

fn client(port: &str) {
    var c = connect(&("User Id=app;Password=app;Data Source=127.0.0.1:" + port + "/lexdb"))
CALLS_HERE
    c.logoff()
}

fn body(st: lexdb_store.Store): int {
    lexdb_exec.bootstrap(&st).unwrap()
    task.scope(fn(s: mut &task.Scope) {
        let ln = net.listen("127.0.0.1:0").unwrap()
        let addr = ln.localAddr()
        let f = s.start(lexdb_tns.acceptLoop, lexdb_tns.AcceptArg{ln: ln, st: st})
        client(&addr[10..len(addr)])
        { let stop = f }
    })
    return 0
}

fn main() {
    lexdb_store.run(lexdb_disk.sim(5), lexdb_store.Options{cacheBytes: 128 * 1024 * 1024, segBytes: 256 * 1024, ckptBytes: 128 * 1024, snapNodes: 50000}, body).unwrap()
}
'''

if __name__ == '__main__':
    main()
