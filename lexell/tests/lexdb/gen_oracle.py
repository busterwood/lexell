def unescape(s):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', 'r': '\r'}.get(m.group(1), m.group(1)), s)


def expects_of(text):
    return [l[len('// expect: '):] for l in text.split('\n') if l.startswith('// expect: ')]


def drop_all(conn):
    cur = conn.cursor()
    # (assertions first: a table one reads is dropped only with CASCADE CONSTRAINTS)
    cur.execute("begin for a in (select assertion_name from user_assertions) loop execute immediate 'drop assertion \"' || a.assertion_name || '\"'; end loop; end;")
    cur.execute("begin for o in (select object_name, object_type from user_objects where object_type in "
                "('TABLE','VIEW','SEQUENCE','PROCEDURE','FUNCTION','PACKAGE','TYPE','SYNONYM','PROPERTY GRAPH') and object_name not like 'BIN$%') loop "
                "begin execute immediate case o.object_type when 'TABLE' then 'drop table \"' || o.object_name || '\" cascade constraints purge' "
                "else 'drop ' || o.object_type || ' \"' || o.object_name || '\"' end; exception when others then null; end; end loop; end;")
    cur.execute('purge recyclebin')


def tx_answer(cur, sqls):
    """statements and queries ("a ;; b") in a transaction rolled back: each answer joined by " / "; after an error, the last part
    (the check) runs after the rollback (tns_subrows)."""
    parts = sqls.split(' ;; ')
    out = []
    failed = False
    for p in parts:
        if failed:
            break
        a = answer(cur, 'q' if p.lower().startswith('select') else 'x', p, True)
        failed = a.startswith('error')
        out.append(a)
    cur.connection.rollback()
    if failed:
        p = parts[-1]
        out.append(answer(cur, 'q' if p.lower().startswith('select') else 'x', p))
    return ' / '.join(out)


def known_diffs():
    """(test, label) -> reason, from oracle_known_diffs.txt: the differences that are lexdb's documented deviations or open
    bugs (design/lexdb-dialect-gaps.md, "Oracle answers checked against Oracle Free"); --check reports them apart."""
    out = {}
    path = os.path.join(HERE, 'oracle_known_diffs.txt')
    if os.path.exists(path):
        for l in open(path, encoding='utf-8'):
            l = l.rstrip('\n')
            if l.strip() and not l.startswith('#'):
                t, label, why = l.split('\t', 2)
                out[(t, label)] = why
    return out


KNOWN = known_diffs()


def report(name, label, sql, lexdb, oracle):
    """print one difference; True if it is a new one (not in oracle_known_diffs.txt)"""
    why = KNOWN.get((name, label))
    if why is not None:
        print('known %s: %s -- %s' % (name, label, why))
        return False
    print('DIFF %s: %s\n  sql:    %s\n  lexdb:  %s\n  oracle: %s' % (name, label, sql[:300], lexdb[:400], oracle[:400]))
    return True


def cell_same(x, y):
    if x == y:
        return True
    try:
        # numbers by value: lib/oracle shows a NUMBER(10,2) with its scale (4000.00), the wire's NUMBER has none (4000), and
        # python's Decimal keeps 40 digits where lexdb's keeps 37
        c = decimal.Context(prec=30)
        return c.plus(decimal.Decimal(x)) == c.plus(decimal.Decimal(y))
    except decimal.InvalidOperation:
        return False


def same(a, b):
    """lexdb's text and the oracle's, equal, or equal cell by cell (numbers by value); a trailing note of lexdb's
    ("(today's plan: ...)") is dropped"""
    a = re.sub(r" \((today's plan|the plan before): .*\)$", '', a)
    if a == b:
        return True
    ha, _, a = a.partition(' = ')
    hb, _, b = b.partition(' = ')
    if ha != hb:
        return False
    ra, rb = a.split(';'), b.split(';')
    if len(ra) != len(rb):
        return False
    for x, y in zip(ra, rb):
        cx, cy = x.split('|'), y.split('|')
        if len(cx) != len(cy) or not all(cell_same(p, q) for p, q in zip(cx, cy)):
            return False
    return True


