#!/usr/bin/env python3
"""Regenerates tests/lexdb/run/exec_time.lxl: lexdb's dates, times,
timestamps and intervals checked against PostgreSQL (design/lexdb.md 9.76).

    python3 lexell/tests/lexdb/gen_time.py "host=/path/to/socket port=5432 user=me dbname=postgres"

Runs each query of time_queries.txt on a PostgreSQL server (TimeZone UTC,
DateStyle ISO, IntervalStyle postgres: the defaults lexdb has), in a new
database, and writes the test: the same queries through lexdb's executor,
expecting PostgreSQL's results (every row, columns joined by |, rows by ;,
NULL as nothing) or its error's SQLSTATE. Needs psql.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
QUERIES = os.path.join(HERE, 'time_queries.txt')
OUT = os.path.join(HERE, 'run', 'exec_time.lxl')


def psql(conn, db, sql, extra=()):
    return subprocess.run(['psql', conn + ' dbname=' + db, '-X', '-At', '-F', '|', '-R', ';', '-v', 'VERBOSITY=sqlstate',
                           '-c', 'set timezone = \'UTC\'', '-c', sql] + list(extra), capture_output=True, text=True)


def main():
    conn = sys.argv[1] if len(sys.argv) > 1 else ''
    base = ' '.join(p for p in conn.split() if not p.startswith('dbname='))
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database if exists lexdb_gen_time'], capture_output=True)
    r = subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'create database lexdb_gen_time'], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('gen_time.py: ' + r.stderr)
    queries = [l.strip() for l in open(QUERIES) if l.strip() and not l.startswith('#')]
    exp = []
    for q in queries:
        r = psql(base, 'lexdb_gen_time', q)
        if r.returncode != 0:
            exp.append('ERROR ' + r.stderr.strip().split('\n')[-1].split()[-1])
        else:
            out = r.stdout.rstrip('\n')
            # the SET's own output comes first
            out = out[len('SET;'):] if out.startswith('SET;') else (out[len('SET'):].lstrip('\n') if out.startswith('SET') else out)
            exp.append(out)
    subprocess.run(['psql', base + ' dbname=postgres', '-X', '-q', '-c', 'drop database lexdb_gen_time'], capture_output=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// lexdb_exec: dates, times, timestamps and intervals, checked against\n')
        f.write('// PostgreSQL 18 (generated by tests/lexdb/gen_time.py from time_queries.txt):\n')
        f.write('// text in and out, BC years and the range\'s ends, infinity, rounding to a\n')
        f.write('// precision, casts, the operators, comparisons across the types, extract,\n')
        f.write('// date_trunc, age and the rest, and the types stored, keyed, indexed,\n')
        f.write('// sorted and aggregated. Each expect line: a query\'s rows, or ERROR and its\n')
        f.write('// SQLSTATE.\n')
        for e in exp:
            f.write('// expect: %s\n' % e)
        f.write(PROGRAM.replace('QUERIES_HERE', '\\n'.join(q.replace('\\', '\\\\').replace('"', '\\"') for q in queries)))
    print('%s: %d queries' % (OUT, len(queries)))


PROGRAM = '''import "strings"
import "../../../cmd/lexdb_store"
import "../../../cmd/lexdb_disk"
import "../../../cmd/lexdb_exec"

const QUERIES = "QUERIES_HERE"

// every row of the last result, columns joined by |, rows by ;; or the tag
fn show(s: mut &lexdb_exec.Session, q: &str): str {
    match s.exec(q) {
        Ok(rs) {
            let r = &rs[len(rs) - 1]
            if !r.hasRows { return r.tag }
            var rows: []str = []
            for row in r.rows {
                var cells: []str = []
                for v in row { append(mut &cells, lexdb_exec.text(&v)) }
                append(mut &rows, strings.join(&cells, "|"))
            }
            return strings.join(&rows, ";")
        }
        Err(e) { return "ERROR " + e.state }
    }
}

fn body(st: lexdb_store.Store): int {
    lexdb_exec.bootstrap(&st).unwrap()
    var s = lexdb_exec.newSession(st)
    let text: str = QUERIES
    for q in strings.lines(&text) { println(show(mut &s, &q)) }
    s.close()
    return 0
}

fn main() {
    lexdb_store.run(lexdb_disk.sim(76), lexdb_store.Options{cacheBytes: 16 * 1024 * 1024, segBytes: 256 * 1024, ckptBytes: 128 * 1024,
                                                           snapNodes: 50000, bufferedPages: false}, body).unwrap()
}
'''

if __name__ == '__main__':
    main()
