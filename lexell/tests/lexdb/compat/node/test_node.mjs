import knex from 'knex';
import oracledb from 'oracledb';

const PG_PORT = Number(process.env.PG_PORT || 15433);
const TDS_PORT = Number(process.env.TDS_PORT || 11433);
const ORA_PORT = Number(process.env.ORA_PORT || 11521);

let passes = 0, fails = 0;

async function run(section, name, fn) {
  try {
    await fn();
    passes++;
    console.log(`  [PASS] ${section} :: ${name}`);
  } catch (e) {
    fails++;
    const msg = String(e?.message || e).replace(/\n/g, ' | ').slice(0, 400);
    console.log(`  [FAIL] ${section} :: ${name} -> ${msg}`);
  }
}

async function testKnex(label, config, tbl) {
  const db = knex(config);
  try {
    await run(label, 'schema createTable + hasTable + columnInfo', async () => {
      if (await db.schema.hasTable(tbl)) {
        await db.schema.dropTable(tbl);
      }
      await db.schema.createTable(tbl, (t) => {
        t.increments('id').primary();
        t.string('name', 100).notNullable().unique();
        t.integer('score').notNullable().defaultTo(0);
      });
      const exists = await db.schema.hasTable(tbl);
      if (!exists) throw new Error('hasTable returned false');
      const info = await db(tbl).columnInfo();
      if (!info || Object.keys(info).length < 3) throw new Error('columnInfo: ' + JSON.stringify(info));
    });

    await run(label, 'insert returning + select + update + trx rollback', async () => {
      const ins = await db(tbl).insert([{ name: 'alpha', score: 10 }, { name: 'beta', score: 20 }]).returning('id');
      if (!ins || ins.length !== 2) throw new Error('returning: ' + JSON.stringify(ins));
      const rows = await db(tbl).where('score', '>=', 10).orderBy('score', 'desc');
      if (rows.length !== 2) throw new Error('rows: ' + JSON.stringify(rows));
      try {
        await db.transaction(async (trx) => {
          await trx(tbl).insert({ name: 'gamma', score: 30 });
          throw new Error('force rollback');
        });
      } catch (e) {
        if (!String(e.message).includes('force rollback')) throw e;
      }
      const after = await db(tbl).count('* as c');
      const cnt = Number(after[0].c ?? after[0].C ?? Object.values(after[0])[0]);
      if (cnt !== 2) throw new Error('expected 2 after rollback, got ' + cnt);
    });
  } finally {
    await db.destroy();
  }
}

async function testNodeOracledb() {
  await run('node-oracledb', 'thin connect + IDENTITY + binds + RETURNING INTO + rollback', async () => {
    const conn = await oracledb.getConnection({
      user: 'sa',
      password: 'sa',
      connectString: `127.0.0.1:${ORA_PORT}/lexdb`,
    });
    try {
      try { await conn.execute('DROP TABLE node_ora_items'); } catch {}
      await conn.execute(
        'CREATE TABLE node_ora_items (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100), score NUMBER)'
      );
      const r1 = await conn.execute(
        'INSERT INTO node_ora_items (name, score) VALUES (:n, :s) RETURNING id INTO :id',
        { n: 'alpha', s: 10, id: { dir: oracledb.BIND_OUT, type: oracledb.NUMBER } },
        { autoCommit: true }
      );
      if (!r1.outBinds?.id || r1.outBinds.id[0] !== 1) throw new Error('bad returning: ' + JSON.stringify(r1.outBinds));
      await conn.execute('INSERT INTO node_ora_items (name, score) VALUES (:1, :2)', ['rolled', 99]);
      await conn.rollback();
      const q = await conn.execute('SELECT id, name, score FROM node_ora_items ORDER BY id');
      if (q.rows.length !== 1 || q.rows[0][1] !== 'alpha') throw new Error('bad rows: ' + JSON.stringify(q.rows));
    } finally {
      await conn.close();
    }
  });
}

console.log('=== Node.js Drivers & Knex Compatibility Suite ===');

await testKnex('Knex-PG', {
  client: 'pg',
  connection: { host: '127.0.0.1', port: PG_PORT, user: 'postgres', database: 'lexdb' },
}, 'kx_pg_items');

await testKnex('Knex-TDS', {
  client: 'mssql',
  connection: {
    server: '127.0.0.1',
    port: TDS_PORT,
    user: 'sa',
    password: 'x',
    database: 'lexdb',
    options: { encrypt: false, trustServerCertificate: true },
  },
}, 'kx_tds_items');

await testNodeOracledb();

console.log(`Node Summary: ${passes}/${passes + fails} passed, ${fails} failed`);
process.exit(fails > 0 ? 1 : 0);
