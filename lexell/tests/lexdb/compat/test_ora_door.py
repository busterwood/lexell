# 2. SQLAlchemy 2 (oracle+oracledb) + Reflection + Alembic
# ============================================================
def test_sqlalchemy_ora():
    import sqlalchemy as sa
    from sqlalchemy import (
        CheckConstraint,
        ForeignKey,
        Identity,
        Index,
        Integer,
        Numeric,
        String,
        func,
        inspect,
        select,
    )
    from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column, relationship, selectinload
    from alembic.autogenerate import compare_metadata
    from alembic.migration import MigrationContext

    engine = sa.create_engine(
        f"oracle+oracledb://{ORA_USER}:{ORA_PASS}@{ORA_HOST}:{ORA_PORT}/?service_name={ORA_SERVICE}"
    )

    class Base(DeclarativeBase):
        pass

    class Org(Base):
        __tablename__ = "sa_ora_orgs"
        id: Mapped[int] = mapped_column(Integer, Identity(), primary_key=True)
        name: Mapped[str] = mapped_column(String(100), unique=True, nullable=False)
        users: Mapped[list["User"]] = relationship(back_populates="org", cascade="all, delete-orphan")

    class User(Base):
        __tablename__ = "sa_ora_users"
        __table_args__ = (
            CheckConstraint("age >= 0", name="ck_sa_ora_users_age"),
            Index("ix_sa_ora_users_org_age", "org_id", "age"),
        )
        id: Mapped[int] = mapped_column(Integer, Identity(), primary_key=True)
        org_id: Mapped[int] = mapped_column(ForeignKey("sa_ora_orgs.id", ondelete="CASCADE"), nullable=False)
        email: Mapped[str] = mapped_column(String(200), nullable=False)
        age: Mapped[int] = mapped_column(Integer, default=20, nullable=False)
        balance: Mapped[decimal.Decimal] = mapped_column(Numeric(12, 2), default=decimal.Decimal("0.00"))
        org: Mapped[Org] = relationship(back_populates="users")

    def t_ddl_and_crud():
        Base.metadata.drop_all(engine)
        Base.metadata.create_all(engine)
        with Session(engine) as s:
            o = Org(name="Acme")
            o.users = [
                User(email="a@acme.com", age=30, balance=decimal.Decimal("100.50")),
                User(email="b@acme.com", age=25, balance=decimal.Decimal("50.25")),
            ]
            s.add(o)
            s.commit()
            assert o.id is not None and o.users[0].id is not None

        with Session(engine) as s:
            orgs = s.scalars(select(Org).options(selectinload(Org.users))).all()
            assert len(orgs) == 1 and len(orgs[0].users) == 2
            page = s.scalars(select(User).order_by(User.age.desc()).offset(1).limit(1)).all()
            assert len(page) == 1 and page[0].email == "b@acme.com", page
            tot = s.scalar(select(func.sum(User.balance)))
            assert decimal.Decimal(str(tot)) == decimal.Decimal("150.75"), tot

    def t_inspector():
        insp = inspect(engine)
        tables = insp.get_table_names()
        assert "sa_ora_orgs" in tables and "sa_ora_users" in tables, tables
        cols = insp.get_columns("sa_ora_users")
        assert len(cols) == 5, cols
        pk = insp.get_pk_constraint("sa_ora_users")
        assert pk["constrained_columns"] == ["id"], pk
        fks = insp.get_foreign_keys("sa_ora_users")
        assert len(fks) == 1 and fks[0]["referred_table"] == "sa_ora_orgs", fks
        ixs = insp.get_indexes("sa_ora_users")
        assert any(i["name"] == "ix_sa_ora_users_org_age" for i in ixs), ixs
        uqs = insp.get_unique_constraints("sa_ora_orgs")
        assert any(u["column_names"] == ["name"] for u in uqs), uqs
        cks = insp.get_check_constraints("sa_ora_users")
        assert len(cks) >= 1, cks

    def t_alembic_autogenerate():
        with engine.connect() as conn:
            ctx = MigrationContext.configure(
                conn,
                opts={
                    "include_object": lambda obj, name, type_, reflected, compare_to: (
                        name is None or name.startswith("sa_ora_")
                    )
                },
            )
            diffs = compare_metadata(ctx, Base.metadata)
            if diffs:
                raise AssertionError(f"unexpected alembic diffs: {diffs}")

    run_test("SQLAlchemy-ORA", "create_all + ORM CRUD + OFFSET/FETCH", t_ddl_and_crud)
    run_test("SQLAlchemy-ORA", "Inspector reflection (cols/PK/FK/IX/UQ/CK)", t_inspector)
    run_test("SQLAlchemy-ORA", "Alembic autogenerate clean diff", t_alembic_autogenerate)


