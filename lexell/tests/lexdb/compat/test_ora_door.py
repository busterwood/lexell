# ============================================================
def test_oracledb():
    import oracledb

    def conn():
        return oracledb.connect(user=ORA_USER, password=ORA_PASS, dsn=f"{ORA_HOST}:{ORA_PORT}/{ORA_SERVICE}")

    def t_basic_and_types():
        with conn() as c:
            cur = c.cursor()
            try:
                cur.execute("DROP TABLE ora_types_t")
            except oracledb.DatabaseError:
                pass
            cur.execute("""
                CREATE TABLE ora_types_t (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    n NUMBER(12,2),
                    d BINARY_DOUBLE,
                    v VARCHAR2(200),
                    cl CLOB,
                    bl BLOB,
                    dt DATE,
                    ts TIMESTAMP,
                    tstz TIMESTAMP WITH TIME ZONE
                )
            """)
            out_id = cur.var(oracledb.NUMBER)
            cur.execute(
                """
                INSERT INTO ora_types_t (n, d, v, cl, bl, dt, ts, tstz)
                VALUES (:n, :d, :v, :cl, :bl, :dt, :ts, :tstz)
                RETURNING id INTO :oid
                """,
                {
                    "n": decimal.Decimal("123.45"),
                    "d": 2.5,
                    "v": "hello",
                    "cl": "long clob text",
                    "bl": b"\x01\x02\x03",
                    "dt": datetime.datetime(2026, 11, 26, 12, 0, 0),
                    "ts": datetime.datetime(2026, 11, 26, 12, 34, 56),
                    "tstz": datetime.datetime(2026, 11, 26, 12, 34, 56, tzinfo=datetime.timezone.utc),
                    "oid": out_id,
                },
            )
            c.commit()
            assert out_id.getvalue()[0] == 1, out_id.getvalue()
            cur.execute("SELECT id, n, d, v, cl, bl, dt, ts, tstz FROM ora_types_t WHERE id = :1", [1])
            row = cur.fetchone()
            assert row[0] == 1 and str(row[1]) in ("123.45", "123.4500000000") and row[3] == "hello", row

    def t_executemany_and_plsql():
        with conn() as c:
            cur = c.cursor()
            try:
                cur.execute("DROP TABLE ora_batch_t")
            except oracledb.DatabaseError:
                pass
            cur.execute("CREATE TABLE ora_batch_t (id NUMBER PRIMARY KEY, name VARCHAR2(50))")
            cur.executemany("INSERT INTO ora_batch_t VALUES (:1, :2)", [(1, "a"), (2, "b"), (3, "c")])
            c.commit()
            out_cnt = cur.var(oracledb.NUMBER)
            cur.execute("BEGIN SELECT COUNT(*) INTO :cnt FROM ora_batch_t; END;", cnt=out_cnt)
            assert int(out_cnt.getvalue()) == 3, out_cnt.getvalue()

    def t_refcursor():
        with conn() as c:
            cur = c.cursor()
            rc = c.cursor()
            cur.execute("BEGIN OPEN :rc FOR SELECT id, name FROM ora_batch_t ORDER BY id; END;", rc=rc)
            rows = rc.fetchall()
            assert rows == [(1, "a"), (2, "b"), (3, "c")], rows

    run_test("oracledb", "types + IDENTITY + RETURNING INTO + CLOB/BLOB", t_basic_and_types)
    run_test("oracledb", "executemany + PL/SQL OUT bind", t_executemany_and_plsql)
    run_test("oracledb", "REF CURSOR OUT bind", t_refcursor)


