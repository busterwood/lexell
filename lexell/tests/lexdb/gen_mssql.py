def sqlcmd(sql):
    p = subprocess.run([os.path.join(ROOT, 'tools', 'mssql_container.sh'), 'sql', '-d', 'master', '-h', '-1', '-f', '65001', '-Q', sql],
                       capture_output=True, text=True)
    if p.returncode != 0 or 'Msg ' in p.stdout:
        sys.exit('gen_mssql.py: ' + p.stdout + p.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--compiler', default=os.path.join(ROOT, 'compiler', 'out', 'lxlc'))
    ap.add_argument('suites', nargs='*')
    a = ap.parse_args()
    dsn = open(os.path.expanduser('~/.obo-mssql-dsn')).read().strip()
    for name in (a.suites or list(SUITES)):
        gen(a.compiler, dsn, name, *SUITES[name])


def lxl_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def gen(compiler, dsn, name, qfile, out, seed, header):
    queries = [l.rstrip('\n') for l in open(os.path.join(HERE, qfile), encoding='utf-8') if l.strip() and not l.startswith('#')]
    prog = PROGRAM.replace('QUERIES_HERE', '\\n'.join(lxl_str(q) for q in queries)).replace('SEED', str(seed))
    path = os.path.join(HERE, 'run', out)
    db = 'lexdb_gen_' + name
    sqlcmd(f"if db_id('{db}') is not null begin alter database {db} set single_user with rollback immediate; drop database {db} end; create database {db}")
    with tempfile.TemporaryDirectory() as tmp:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(prog)
        exe = os.path.join(tmp, 'gen')
        r = subprocess.run([compiler, path, '--native', '-o', exe], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit('gen_mssql.py: compile: ' + r.stdout + r.stderr)
        env = dict(os.environ, LEXDB_MSSQL=re.sub(r';?Database=[^;]*', '', dsn, flags=re.I) + ';Database=' + db)
        r = subprocess.run([exe], capture_output=True, text=True, env=env, cwd=tmp)
        if r.returncode != 0:
            sys.exit('gen_mssql.py: run: ' + r.stdout + r.stderr)
    sqlcmd(f"alter database {db} set single_user with rollback immediate; drop database {db}")
    lines = r.stdout.rstrip('\n').split('\n')
    if len(lines) != len(queries):
        sys.exit('gen_mssql.py: %d results for %d batches' % (len(lines), len(queries)))
    with open(path, 'w', encoding='utf-8') as f:
        for h in header:
            f.write('// ' + h + '\n')
        for l in lines:
            f.write('// expect: %s\n' % l)
        f.write(prog)
    print('%s: %d batches' % (path, len(queries)))


PROGRAM = '''import "os"
import "strings"
import "task"
import "net"
import "sqlserver"
import "../../../cmd/lexdb_store"
import "../../../cmd/lexdb_disk"
import "../../../cmd/lexdb_exec"
import "../../../cmd/lexdb_wire"
import "../../../cmd/lexdb_tds"

const QUERIES = "QUERIES_HERE"

fn rows(r: &sqlserver.Rows): str {
    var names: []str = []
    for j in 0..r.columnCount() { append(mut &names, r.columnName(j).unwrap()) }
    var out: []str = []
    for i in 0..r.rowCount() {
        var cells: []str = []
        for j in 0..r.columnCount() {
            match r.value(i, j) {
                Ok(v) { append(mut &cells, v.toStr()) }
                Err(e) { append(mut &cells, "error " + e.code.toStr()) }
            }
        }
        append(mut &out, strings.join(&cells, "|"))
    }
    return strings.join(&names, ",") + ": " + strings.join(&out, ";")
}

// a batch's result sets and row counts, in order; or its error
fn show(c: mut &sqlserver.Conn, q: &str): str {
    match c.queryAll(q.toStr(), &[]) {
        Ok(r) {
            var parts: []str = []
            var shown = 0
            for n in r.counts {
                if n.resultSet >= 0 {
                    append(mut &parts, rows(&r.sets[n.resultSet]))
                    shown += 1
                } else {
                    append(mut &parts, "(" + n.rows.toStr() + ")")
                }
            }
            if shown == 0 { for s in r.sets { append(mut &parts, rows(&s)) } }
            if len(parts) == 0 { return "ok" }
            return strings.join(&parts, " / ")
        }
        Err(e) { return "error " + e.code.toStr() }
    }
}

fn batches(dsn: &str) {
    match sqlserver.connect(dsn.toStr()) {
        Ok(c0) {
            var c = c0
            let text: str = QUERIES
            for q in strings.lines(&text) { println(show(mut &c, &q)) }
            c.close()
        }
        Err(e) { println("connect: error " + e.code.toStr() + " " + e.msg) }
    }
}

fn body(st: lexdb_store.Store): int {
    lexdb_exec.bootstrap(&st).unwrap()
    task.scope(fn(s: mut &task.Scope) {
        let ln = net.listen("127.0.0.1:0").unwrap()
        let addr = ln.localAddr()
        lexdb_wire.configure(&st, &lexdb_wire.noAuth()).unwrap()
        let f = s.start(lexdb_tds.acceptLoop, lexdb_tds.AcceptArg{ln: ln, st: st})
        batches(&("Server=127.0.0.1," + addr[10..len(addr)] + ";UID=sa;PWD=x;Encrypt=no"))
        { let stop = f }
    })
    return 0
}

fn main() {
    // LEXDB_MSSQL: the oracle, for the expect lines (gen_mssql.py)
    match os.env("LEXDB_MSSQL") {
        Some(dsn) { batches(&dsn) }
        None {
            lexdb_store.run(lexdb_disk.sim(SEED), lexdb_store.Options{cacheBytes: 64 * 1024 * 1024, segBytes: 256 * 1024, ckptBytes: 128 * 1024,
                                                                     snapNodes: 50000, bufferedPages: false}, body).unwrap()
        }
    }
}
'''

if __name__ == '__main__':
    main()
