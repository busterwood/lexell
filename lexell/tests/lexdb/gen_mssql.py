#!/usr/bin/env python3
"""Regenerates lexdb's tests that are checked against SQL Server: each a file
of T-SQL batches, run on the oracle (tools/mssql_container.sh) through
lib/sqlserver, and a test that runs them through lexdb's TDS endpoint (in
the same process) with the same client, expecting the oracle's answers.
design/lexdb-tds.md, S3.

    python3 lexell/tests/lexdb/gen_mssql.py [--compiler lexell/compiler/out/lxlc] [SUITE ...]

The test program is the generator's too: run with LEXDB_MSSQL set to a
connection string it talks to that server, and its output becomes the
expect lines. Each suite runs in a new database (lexdb_gen_NAME) of the
oracle, made with the server's default collation (SQL_Latin1_General_CP1_
CI_AS). A batch is one line of the queries file (# lines are comments).
Its result: per statement, in order, a result set's column names and rows
(names: v|v;v|v, NULL as NULL, text quoted) or a change's row count ((n)),
joined by " / "; or the batch's error number. The oracle's connection
string is ~/.obo-mssql-dsn.
"""
